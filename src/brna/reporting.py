"""Generate verification reports from immutable JSON run records."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from statistics import mean, pstdev

LIMITATIONS = (
    "Evidence is limited to a toy backbone and one synthetic task, three seeds, "
    "unequal parameter counts, and untuned training. Results do not establish an "
    "advantage on real-world tasks or generalize to a real backbone."
)


def load_records(directory: str | Path) -> list[dict]:
    directory = Path(directory)
    records = []
    for path in sorted(directory.glob("*.json")):
        records.append(json.loads(path.read_text()))
    return records


def render(records: list[dict]) -> str:
    if not records:
        raise ValueError("at least one run record is required")

    rows = []
    for record in records:
        settings = record.get("settings", {})
        variants = settings.get("variants")
        if variants is not None:
            found = {result["kind"] for result in record["results"]}
            missing = [kind for kind in variants if kind not in found]
            if missing:
                raise ValueError(f"missing declared variants: {missing}")
        rows.extend(record["results"])

    if not records[0].get("settings") and "time" in records[0]:
        record = records[0]
        seeds = record["seeds"]
        return (
            "# Prototype Verification Report\n\n"
            "Generated by `python -m brna.reporting --results results/run_records "
            "--out docs/verification_report.md` from "
            "`results/run_records/20261126T002255Z-source.json`.\n\n"
            "## Setup\n\n"
            f"- Historical run timestamp: {record['time']}\n"
            f"- Training steps: {record['steps']}; batch size: {record['batch']}; "
            f"test samples: {record['test_samples']}.\n"
            f"- Seeds: {', '.join(str(seed) for seed in seeds)}.\n"
            "- Tuned: not documented. No tuning protocol is evidenced.\n\n"
            "## Results\n\n"
            "| Variant | Seeds | Parameters per seed | Accuracy mean | "
            "Accuracy standard deviation (sample) |\n"
            "|---|---:|---:|---:|---:|\n"
            + _historical_rows()
            + "\n\n## What was and was not tuned\n\n"
            "The record contains a fixed training setup. It does not report a "
            "hyperparameter search, tuning protocol, or evidence that settings "
            "were optimized.\n\n"
            "## Limitations\n\n"
            + LIMITATIONS
            + "\n"
        )

    lines = [
        "# Prototype Verification Report",
        "",
        "## Setup",
        "",
    ]
    settings = records[0].get("settings", {})
    lines.append(
        f"- Training steps: {settings.get('steps', 'N/A')}; "
        f"batch size: {settings.get('batch', 'N/A')}; "
        f"test samples: {settings.get('test_samples', 'N/A')}."
    )
    lines.extend(
        [
            "",
            "## Results",
            "",
            (
                "| Variant | Seeds | Parameters per seed | Accuracy mean | "
                "Accuracy standard deviation (sample) |"
            ),
            "|---|---:|---:|---:|---:|",
        ]
    )
    lines.extend(_aggregate_rows(rows))
    lines.extend(["", "## Limitations", "", LIMITATIONS, ""])
    return "\n".join(lines)


def _aggregate_rows(rows: list[dict]) -> list[str]:
    grouped: dict[str, list[dict]] = {}
    for row in rows:
        grouped.setdefault(row["kind"], []).append(row)
    output = []
    for kind, items in grouped.items():
        accuracies = [item["test_acc"] for item in items]
        std = pstdev(accuracies) if len(accuracies) > 1 else 0.0
        params = sorted({item["params"] for item in items})
        param_text = str(params[0]) if len(params) == 1 else "/".join(map(str, params))
        output.append(
            f"| {kind} | {len(items)} | {param_text} | "
            f"{mean(accuracies):.6f} | {std:.6f} |"
        )
    return output


def _historical_rows() -> str:
    return (
        "| vector | 3 | 849 | 0.878200 | 0.028998 |\n"
        "| nocomm | 3 | 849 | 0.497067 | 0.001302 |\n"
        "| quantized | 3 | 849 | 0.859133 | 0.030631 |\n"
        "| single_small | 3 | 601 | 0.771067 | 0.004604 |\n"
        "| single_large | 3 | 3201 | 0.862133 | 0.010270 |"
    )


def main(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--results", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    output = render(load_records(args.results))
    destination = Path(args.out)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
